# Moment inside the effect's own window to photograph (fraction of the window).
MOMENT = {"messages": 0.9, "terminal": 0.8, "whip": 0.5, "sticker-swipe": 0.5, "speed-lines": 0.4, "lens": 0.6, "subtitles": 0.12, "flash": 0.1, "shake": 0.15, "punch-in": 0.5, "glitch": 0.3, "iris": 0.55, "countdown": 0.2, "confetti": 0.25,
          "float-up": 0.6, "rgb-split": 0.5, "pulse": 0.02, "letterbox": 0.5}


def _window(eff):
    start = 1.0
    return start, start + eff.default_len


def thumb(eff, clip, size=(360, 640)):
    start, end = _window(eff)
    entry = {"fx": eff.name, "start": start, "end": end, **SHOWCASE.get(eff.name, {})}
    at = start + (end - start) * MOMENT.get(eff.name, 0.55)
    imgs, _ = R.stills(clip, lambda d: P.build([entry], None), [at], face=demo.FACE)
    return Image.fromarray(imgs[0]).resize(size, Image.LANCZOS)


def write_catalog(path):
    load_library()
    lines = ["# Effect catalog", "", "_Generated by `reelcraft catalog`. Do not edit by hand._", "",
             f"{len(REGISTRY)} effects across {len(CATEGORIES)} categories. Every option below can be set in a plan or with `-e 'name@start-end key=value'`.", ""]
    for cat, effs in by_category().items():
        lines += [f"## {cat.title()}", "", f"_{CATEGORY_BLURB[cat]}_", ""]
        for e in effs:
            lines += [f"### `{e.name}`", "", e.summary, ""]
            meta = [f"default length {e.default_len}s"] + (["follows the face"] if e.face else [])
            if e.aliases:
                meta.append("aliases: " + ", ".join(f"`{a}`" for a in e.aliases))
            lines += ["_" + " · ".join(meta) + "_", ""]
            if e.params:
                lines += ["| Option | Default | What it does |", "|---|---|---|"]
                for p in e.params:
                    ch = f" ({' / '.join(map(str, p.choices))})" if p.choices else ""
                    lines.append(f"| `{p.name}` | `{p.default!r}` | {p.doc}{ch} |")
                lines.append("")
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    open(path, "w").write("\n".join(lines))


def write_gallery(outdir, per_effect=False):
    load_library()
    os.makedirs(outdir, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        clip = os.path.join(tmp, "demo.mp4")
        demo.make_demo_clip(clip, 6)
        effs = [e for c in CATEGORIES for e in by_category()[c]]
        tw, th, lab = 270, 480, 44
        cols = 8
        rows = -(-len(effs) // cols)
        sheet = Image.new("RGB", (cols * tw, rows * (th + lab)), (17, 17, 20))
        d = ImageDraw.Draw(sheet)
        f = font("ui-semi", 17)
        for i, e in enumerate(effs):
            im = thumb(e, clip, (tw, th))
            x, y = (i % cols) * tw, (i // cols) * (th + lab)
            sheet.paste(im, (x, y))
            d.text((x + 12, y + th + 12), e.name, font=f, fill=(238, 232, 218))
            if per_effect:
                im.save(os.path.join(outdir, f"{e.name}.jpg"), quality=88)
            print("  ", e.name)
        sheet.save(os.path.join(outdir, "gallery.jpg"), quality=86)
        print("wrote", os.path.join(outdir, "gallery.jpg"))
        write_templates_sheet(clip, outdir)
    write_recipe_sheets(outdir)


def write_templates_sheet(clip, outdir):
    """One frame from each built-in template, at the moment it looks best, on a labelled sheet."""
    tpls = {k: v for k, v in T.available().items() if v["source"] == "built-in"}
    tw, th, lab = 300, 533, 62
    cols = 6
    rows = -(-len(tpls) // cols)
    sheet = Image.new("RGB", (cols * tw, rows * (th + lab)), (17, 17, 20))
    d = ImageDraw.Draw(sheet)
    f1, f2 = font("ui-semi", 18), font("ui", 14)
    for i, (name, t) in enumerate(sorted(tpls.items())):
        entries = T.entries(name)
        imgs, _ = R.stills(clip, lambda dur: P.build(entries, dur), [min(MOMENT_T.get(name, 0.58), 0.95) * 6], face=demo.FACE)
        x, y = (i % cols) * tw, (i // cols) * (th + lab)
        sheet.paste(Image.fromarray(imgs[0]).resize((tw, th), Image.LANCZOS), (x, y))
        d.text((x + 12, y + th + 10), name, font=f1, fill=(238, 232, 218))
        d.text((x + 12, y + th + 36), t["niche"], font=f2, fill=(150, 146, 138))
    path = os.path.join(outdir, "templates.jpg")
    sheet.save(path, quality=86)
    print("wrote", path)


# Where in each template (0..1 of the clip) to take its picture.
