def write_recipe_sheets(outdir):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    tw, th, lab = 240, 427, 40
    with tempfile.TemporaryDirectory() as tmp:
        clip = os.path.join(tmp, "demo.mp4")
        demo.make_demo_clip(clip, 100)
        for name, moments in RECIPES.items():
            import json
            entries = [e for e in json.load(open(os.path.join(root, "examples", name + ".json")))["effects"] if e["fx"] != "subtitles"]
            imgs, _ = R.stills(clip, lambda d: P.build(entries, d), [t for t, _ in moments], face=demo.FACE)
            sheet = Image.new("RGB", (len(moments) * tw, th + lab), (17, 17, 20))
            d = ImageDraw.Draw(sheet)
            f = font("ui-semi", 15)
            for i, (im, (t, label)) in enumerate(zip(imgs, moments)):
                sheet.paste(Image.fromarray(im).resize((tw, th), Image.LANCZOS), (i * tw, 0))
                d.text((i * tw + 10, th + 11), f"{t:g}s  {label}", font=f, fill=(238, 232, 218))
            path = os.path.join(outdir, f"recipe-{name}.jpg")
            sheet.save(path, quality=88)
            print("wrote", path)


def clips_len(path):
    from reelcraft.core import media as M
    return M.probe(path).duration


def contact_strip(video, times, labels, out, thumb_w=270):
    """Frames from a (rendered) video at the given times, side by side with labels. Handy for READMEs and reviews."""
    from reelcraft.core import media as M
    m = M.probe(video)
    W = thumb_w
    H = int(round(W * m.height / m.width))
    lab = 46
    sheet = Image.new("RGB", (len(times) * W, H + lab), (17, 17, 20))
    d = ImageDraw.Draw(sheet)
    f = font("ui-semi", 15)
    for i, t in enumerate(times):
        fr = next(M.frames(m, W * 2, H * 2, m.fps, start=t, count=1), None)
        if fr is None:
            raise M.MediaError(f"no frame at {t}s")
        sheet.paste(Image.fromarray(fr).resize((W, H), Image.LANCZOS), (i * W, 0))
        text = f"{t:g}s  {labels[i]}" if i < len(labels) and labels[i] else f"{t:g}s"
        d.text((i * W + 12, H + 14), text, font=f, fill=(238, 232, 218))
    sheet.save(out, quality=90)
